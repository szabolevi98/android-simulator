/* AOSP frameworks/opt/timezonepicker as __APP__ ships it (__IMAGE__): Calendar's TimeZonePickerDialog.
   Generated by docs/timezonepicker.py from docs/timezonepicker.template.js; the data is the image's own: the Calendar's
   assets/zone.tab and assets/backward, its timezone_rename_* and backup_country_* arrays and strings, the image's
   __TZDATA__ (raw offsets, transitions from 2020, whether a zone still uses DST, the six-transition rule signature
   TimeZoneInfo.hasSameRules compares) and __ICU__ (TimeZone.getDisplayName's long names, Locale.getDisplayCountry).
   - TimeZoneData: zone.tab's zones in order with their country names, the event's zone added where its (backward-
     mapped) id comes up, a zone dropped when one with the same rules is already there for the same country; the
     Etc/GMT zones without a country; sorted by the offset now (largest first), the country, the standard name; then
     the renames, the display names (daylight when the event's time is in DST) and the groups by country and by hour.
   - TimeZoneResultAdapter: with no filter the event's zone then the recent ones (preferences_recent_timezones, at most
     three, newest first); a GMT or a country filter lists that group; nothing matching shows no_results_found. A row
     is time_zone_item: the name, the time there now with "GMT+1" (and the sun when the zone uses DST), the country.
   - TimeZoneFilterTypeAdapter: the typed text (trimmed, lower case) as an hour ("1", "+5", "-3", "gmt+2": 1 also
     offers 10-19) and as the start of a country name, of a word in it or of its initials ("usa" also matches United
     States); the suggestions drop down under the field, a pick puts its text in the field and filters the list.
   - TimeZonePickerUtils.getGmtDisplayName: the edit screen's button, "Central European Standard Time  GMT+1 ☀".
   State: {defaultId, millis, query, filter: {type, str, time}, drop: [[type, text, time], ...] | null}. */
(() => {
  'use strict';
  const DATA = __DATA__;
  const LANGS = ['en', 'hu', 'de', 'fr', 'es'];
  const NONE = 0, COUNTRY = 1, GMT = 3, EMPTY = -1, EMPTY_INDEX = -100, OFFSET_ARRAY_OFFSET = 20, MAX_RECENT = 3;
  const e = value => String(value ?? '').replace(/[&<>"']/g, c => ({'&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'}[c]));
  const li = lang => Math.max(0, LANGS.indexOf(String(lang || 'en').slice(0, 2)));
  const S = (lang, key) => DATA.strings[key][li(lang)];
  // TimeZone.getTimeZone: an old id reads its backward-mapped zone, an unknown one is GMT.
  const zone = id => DATA.zones[id] ? id : DATA.zones[DATA.links[id]] ? DATA.links[id] : 'GMT';
  // A zone: [raw minutes, useDaylightTime, rule signature, name tuple (std, dst per language), transition table]; a
  // table: [offset and DST flag in 2020, [[offset, dst], ...], "base-36 minutes since the last one.kind,..."].
  const decoded = new Map();
  function transitions(index) {
    if (!decoded.has(index)) {
      const [, , kinds, steps] = DATA.transitions[index];
      let t = DATA.from;
      decoded.set(index, steps ? steps.split(',').map(step => { const [delta, kind] = step.split('.'); t += parseInt(delta, 36); return [t, ...kinds[Number(kind)]]; }) : []);
    }
    return decoded.get(index);
  }
  function state(id, ms) {
    const row = DATA.zones[zone(id)], table = DATA.transitions[row[4]], t = Math.floor(ms / 60000);
    let off = table[0], dst = table[1];
    for (const [time, o, d] of transitions(row[4])) { if (time > t) break; off = o; dst = d; }
    return {off, dst: !!dst};
  }
  const offsetMinutes = (id, ms) => state(id, ms).off;
  // libcore's createGmtOffsetString(true, true, offset) for zones ICU has no name for.
  const gmtString = minutes => `GMT${minutes < 0 ? '-' : '+'}${String(Math.floor(Math.abs(minutes) / 60)).padStart(2, '0')}:${String(Math.abs(minutes) % 60).padStart(2, '0')}`;
  // TimeZone.getDisplayName(daylight, LONG or SHORT, locale): daylight only when the zone still uses DST. A zone's names
  // are [long std, long dst, short std, short dst] per language.
  function displayName(id, lang, daylight, short = false) {
    const row = DATA.zones[zone(id)], useDaylight = daylight && !!row[1], name = DATA.zoneNames[row[3]][li(lang) * 4 + (short ? 2 : 0) + (useDaylight ? 1 : 0)];
    return name >= 0 ? DATA.names[name] : gmtString(row[0] + (useDaylight ? 60 : 0));
  }
  // The wall date and time in a zone at an instant: {date: 'YYYY-MM-DD', time: 'HH:MM'}.
  function wall(id, ms) {
    const iso = new Date(ms + offsetMinutes(id, ms) * 60000).toISOString();
    return {date: iso.slice(0, 10), time: iso.slice(11, 16)};
  }
  // TimeZonePickerUtils.appendGmtOffset: "GMT+1", "GMT-3:30".
  const gmtOffset = minutes => `GMT${minutes < 0 ? '-' : '+'}${Math.floor(Math.abs(minutes) / 60)}${Math.abs(minutes) % 60 ? ':' + String(Math.abs(minutes) % 60).padStart(2, '0') : ''}`;
  const countryName = (cc, lang) => DATA.names[DATA.countries[cc][li(lang)]];
  const renamed = (id, lang) => DATA.renames[id] ? DATA.names[DATA.renames[id][li(lang)]] : null;

  // TimeZoneData for one event (its zone and start time), the language and the time now.
  const cache = new Map();
  function tzData(defaultId, millis, lang, now) {
    const key = [defaultId, millis, lang, Math.floor(now / 60000)].join('|');
    if (cache.has(key)) return cache.get(key);
    const list = [], info = (id, country) => ({id: DATA.zones[id] || DATA.links[id] ? id : 'GMT', country, sig: DATA.zones[zone(id)][2], nowOff: offsetMinutes(id, now)});
    const identical = tzi => list.findIndex(other => other.sig === tzi.sig && (other.country == null ? tzi.country == null : other.country === tzi.country));
    let alternate = defaultId, defaultCountry = null, defaultInfo = null;
    if (defaultId && DATA.links[defaultId]) alternate = DATA.links[defaultId];
    for (const [id, cc] of DATA.zoneTab) {
      const country = countryName(cc, lang);
      if (defaultId && defaultCountry == null && id === alternate) {
        defaultCountry = country; defaultInfo = info(defaultId, country);
        const at = identical(defaultInfo);
        if (at === -1) list.push(defaultInfo); else list.splice(at, 0, defaultInfo);
      }
      const tzi = info(id, country);
      if (identical(tzi) === -1) list.push(tzi);
    }
    for (const id of DATA.etc) { const tzi = info(id, null); if (identical(tzi) === -1) list.push(tzi); }
    // TimeZoneInfo.compareTo (no display names yet, so the standard names decide last).
    list.sort((a, b) => {
      if (a.nowOff !== b.nowOff) return b.nowOff < a.nowOff ? -1 : 1;
      if (a.country == null && b.country != null) return 1;
      if (b.country == null) return -1;
      if (a.country !== b.country) return a.country < b.country ? -1 : 1;
      const x = displayName(a.id, lang, false), y = displayName(b.id, lang, false);
      return x < y ? -1 : x > y ? 1 : 0;
    });
    const byCountry = new Map(), byOffset = new Map(), hasHour = new Set();
    list.forEach((tzi, i) => {
      tzi.name = renamed(tzi.id, lang) ?? displayName(tzi.id, lang, state(tzi.id, millis).dst);
      if (!byCountry.has(tzi.country)) byCountry.set(tzi.country, []);
      byCountry.get(tzi.country).push(i);
      const hour = OFFSET_ARRAY_OFFSET + Math.trunc(tzi.nowOff / 60);
      hasHour.add(hour);
      if (!byOffset.has(hour)) byOffset.set(hour, []);
      byOffset.get(hour).push(i);
    });
    const result = {list, byCountry, byOffset, hasHour, defaultIndex: defaultInfo ? list.indexOf(defaultInfo) : -1, defaultId};
    cache.clear(); cache.set(key, result);
    return result;
  }
  const hasTimeZonesInHrOffset = (tzd, hour) => tzd.hasHour.has(OFFSET_ARRAY_OFFSET + hour);

  // TimeZoneFilterTypeAdapter.ArrayFilter.performFiltering: [type, text, hour] suggestions, or null.
  function suggestions(tzd, query) {
    const prefix = String(query ?? '').trim().toLowerCase();
    if (!prefix) return null;
    const filtered = [];
    const start = prefix.startsWith('gmt') ? 3 : 0;
    const num = parseNum(prefix, start);
    if (num !== null) {
      const positiveOnly = prefix.length > start && prefix[start] === '+';
      let n = num;
      if (n >= 0) {
        if (n === 1) for (let i = 19; i >= 10; i--) if (hasTimeZonesInHrOffset(tzd, i)) filtered.push([GMT, 'GMT+' + i, i]);
        if (hasTimeZonesInHrOffset(tzd, n)) filtered.push([GMT, 'GMT+' + n, n]);
        n *= -1;
      }
      if (!positiveOnly && n !== 0) {
        if (hasTimeZonesInHrOffset(tzd, n)) filtered.push([GMT, 'GMT' + n, n]);
        if (n === -1) for (let i = -10; i >= -19; i--) if (hasTimeZonesInHrOffset(tzd, i)) filtered.push([GMT, 'GMT' + i, i]);
      }
    }
    const countries = [];
    for (const country of tzd.byCountry.keys()) {
      if (!country) continue;
      const lower = country.toLowerCase();
      let match = lower.startsWith(prefix) || (lower[0] === prefix[0] && initials(prefix, lower));
      if (!match && lower.includes(' ')) match = lower.split(' ').some(word => word.startsWith(prefix));
      if (match) countries.push(country);
    }
    countries.sort();
    for (const country of countries) filtered.push([COUNTRY, country, 0]);
    return filtered.length ? filtered : null;
  }
  // isStartingInitialsFor: the typed letters are the initials of the name's words ("usa" also for United States).
  function initials(prefix, string) {
    let at = 0, wordBreak = true;
    for (const ch of string) {
      if (!/\p{L}/u.test(ch)) { wordBreak = true; continue; }
      if (wordBreak) {
        if (prefix[at++] !== ch) return false;
        if (at === prefix.length) return true;
        wordBreak = false;
      }
    }
    return prefix === 'usa' && string === 'united states';
  }
  // parseNum: an optional sign and one or two digits, nothing else ("gmt" alone has no number).
  function parseNum(str, index) {
    let i = index, sign = 1;
    if (i >= str.length) return null;
    let ch = str[i++];
    if (ch === '-' || ch === '+') {
      if (ch === '-') sign = -1;
      if (i >= str.length) return null;
      ch = str[i++];
    }
    if (!/[0-9]/.test(ch)) return null;
    let num = Number(ch);
    if (i < str.length) {
      ch = str[i++];
      if (!/[0-9]/.test(ch)) return null;
      num = num * 10 + Number(ch);
    }
    return i === str.length ? sign * num : null;
  }

  // TimeZoneResultAdapter.onSetFilter: the rows (indices into the list, EMPTY_INDEX for "No results found").
  function rows(tzd, filter, recents) {
    if (filter.type === EMPTY) return [EMPTY_INDEX];
    if (filter.type === GMT) return tzd.byOffset.get(OFFSET_ARRAY_OFFSET + filter.time) || [];
    if (filter.type === COUNTRY) return tzd.byCountry.get(filter.str) || [];
    const out = [];
    if (tzd.defaultIndex !== -1) out.push(tzd.defaultIndex);
    for (let i = recents.length - 1; i >= 0; i--) {
      if (recents[i] && recents[i] !== tzd.defaultId) {
        const index = tzd.list.findIndex(tzi => tzi.id === recents[i]);
        if (index !== -1) out.push(index);
      }
    }
    return out;
  }
  // saveRecentTimezone: the picked zone goes last, the oldest drop out to keep three.
  function saveRecent(recents, id) {
    if (!recents?.length) return [id];
    const kept = [...new Set(recents.filter(tzId => tzId !== id))];
    while (kept.length >= MAX_RECENT) kept.shift();
    return [...kept, id];
  }
  // The time there now ("3:45 PM" / "15:45"), the offset in grey and the sun (DateUtils.formatDateRange, SHOW_TIME).
  function timeLine(id, ctx) {
    const off = offsetMinutes(id, ctx.now), local = new Date(ctx.now + off * 60000);
    const time = local.toLocaleTimeString(ctx.locale, {timeZone: 'UTC', hour: 'numeric', minute: '2-digit', hour12: !ctx.hour24});
    return `${e(time)}  <i>${e(gmtOffset(off))}</i>${DATA.zones[zone(id)][1] ? ' <b>☀</b>' : ''}`;
  }

  window.TimeZonePicker = {
    // The edit screen's time zone button: the name at the event's time, its offset then, the sun for DST zones.
    label(id, millis, lang) {
      const name = renamed(zone(id), lang) ?? displayName(id, lang, state(id, millis).dst);
      return `${e(name)}  <i>${e(gmtOffset(offsetMinutes(id, millis)))}</i>${DATA.zones[zone(id)][1] ? ' <b>☀</b>' : ''}`;
    },
    description: lang => S(lang, 'accessibility_pick_time_zone'),
    // The event's start (a wall date and time in its zone) as milliseconds.
    millis(id, date, time) {
      const wall = Date.parse(`${date}T${time || '00:00'}:00Z`);
      if (Number.isNaN(wall)) return Date.now();
      return wall - offsetMinutes(id, wall - offsetMinutes(id, wall) * 60000) * 60000;
    },
    open: (defaultId, millis) => ({defaultId, millis, query: '', filter: {type: NONE, str: null, time: 0}, drop: null}),
    // ctx: {lang, locale, now, hour24, recents}
    render(st, ctx) {
      const tzd = tzData(st.defaultId, st.millis, ctx.lang, ctx.now);
      const items = rows(tzd, st.filter, ctx.recents || []).map(index => {
        if (index === EMPTY_INDEX) return `<div class="tzp-empty"><div class="tzp-row"><span class="tzp-name">&nbsp;</span><span class="tzp-time">&nbsp;</span><span class="tzp-country">&nbsp;</span></div><p>${e(S(ctx.lang, 'no_results_found'))}</p></div>`;
        const tzi = tzd.list[index];
        return `<button type="button" class="tzp-row" data-action="tzp-pick" data-id="${e(tzi.id)}"><span class="tzp-name">${e(tzi.name)}</span><span class="tzp-time">${timeLine(tzi.id, ctx)}</span><span class="tzp-country${tzi.country == null ? ' none' : ''}">${e(tzi.country ?? ' ')}</span></button>`;
      }).join('');
      const hint = st.query ? '' : `<span class="tzp-hint"><img src="assets/tzp-ic_search_holo_light.png" alt="">${e(S(ctx.lang, 'hint_time_zone_search'))}</span>`;
      const clear = st.query ? `<button type="button" class="tzp-clear" data-action="tzp-clear" aria-label="${e(S(ctx.lang, 'searchview_description_clear'))}"><img src="assets/tzp-ic_clear_search_holo_light.png" alt=""></button>` : '';
      const drop = st.drop ? `<div class="tzp-drop" role="listbox">${st.drop.map((item, i) => `<button type="button" role="option" data-action="tzp-filter" data-id="${i}">${e(item[1])}</button>`).join('')}</div>` : '';
      return `<div class="settings-dialog-scrim" data-action="close-overlay"></div><div class="tzp" role="dialog" data-no-translate><div class="tzp-search"><input class="tzp-input" type="text" data-tzp-search data-action="tzp-field" value="${e(st.query)}" autocomplete="off" spellcheck="false" aria-label="${e(S(ctx.lang, 'hint_time_zone_search'))}">${hint}${clear}${drop}</div><div class="tzp-list">${items}</div></div>`;
    },
    // Typing: new suggestions, or the list's "No results found" / no filter when there are none.
    input(st, value, ctx) {
      st.query = value;
      const found = suggestions(tzData(st.defaultId, st.millis, ctx.lang, ctx.now), value);
      st.drop = found;
      if (!found) st.filter = {type: value ? EMPTY : NONE, str: null, time: 0};
    },
    // Tapping the field with no suggestions showing filters the text again.
    focus(st, ctx) { if (!st.drop && st.query) TimeZonePicker.input(st, st.query, ctx); },
    filter(st, index) {
      const item = st.drop?.[Number(index)];
      if (!item) return;
      st.query = item[1]; st.drop = null; st.filter = {type: item[0], str: item[1], time: item[2]};
    },
    clear(st) { st.query = ''; st.drop = null; st.filter = {type: NONE, str: null, time: 0}; },
    saveRecent,
    wall,
    // Utils.getDisplayedTimezone: the short name of the device's zone at the event's start ("CET", "GMT+01:00"); an id
    // the image does not know is shown as it is.
    shortName: (id, ms, lang) => DATA.zones[id] || DATA.links[id] ? displayName(id, lang, state(id, ms).dst, true) : id,
    // For tests: the list as the dialog builds it.
    data: (defaultId, millis, lang, now) => tzData(defaultId, millis, lang, now),
    suggestions: (defaultId, millis, lang, now, query) => suggestions(tzData(defaultId, millis, lang, now), query)
  };
})();
