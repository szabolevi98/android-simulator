"""Android 2.1: copies the image's drawables into versions/2.1/assets and writes versions/2.1/ec-ninepatch.css.

    python docs/tools/ec-assets.py

docs/data/ec-assets.tsv lists one file per line: <output name> <TAB> <APK under _aosp/passion/system> <TAB> <resource>,
e.g. "fw-statusbar_background.9.png	framework/framework-res.apk	drawable/statusbar_background". The resource is taken
in the first density the APK has of hdpi, nodpi, mdpi, ldpi (the Nexus One is hdpi) and copied byte for byte.

Every nine-patch gets a class in ec-ninepatch.css: .np-<output name without .9.png> draws it as a CSS border image.
Compiled nine-patches keep their stretch areas and padding in the PNG's npTc chunk (no 1 px guide border): the slices
are the parts outside the first and last stretch area, the border widths are those slices in dp (hdpi and nodpi: 1.5 px
per dp, mdpi or no qualifier: 1, ldpi: 0.75 — Android scales those up to hdpi; written as calc(n * var(--dp))), and the padding is the nine-patch padding minus the slice, so the content sits where
Android puts it. .npp-<name> is the nine-patch's whole padding, for a view whose background it is. Run it again after changing the list; the CSS is generated, do not edit it by hand."""
import os, struct, sys, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
SYSTEM = ROOT + '_aosp/passion/system/'
OUT = ROOT + 'versions/2.1/assets/'
CSS = ROOT + 'versions/2.1/ec-ninepatch.css'
DENSITIES = ['-hdpi', '', '-nodpi', '-mdpi', '-ldpi']
# Contacts / Phone keep their touchscreen resources under -finger (drawable-hdpi-finger).
DENSITIES = [d for base in DENSITIES for d in (base, base + '-finger')]


def find(z, resource):
    kind, name = resource.split('/', 1)
    names = set(z.namelist())
    for d in DENSITIES:
        for ext in ('.9.png', '.png', '.jpg', '.gif', '.xml', '.html'):
            path = f'res/{kind}{d}/{name}{ext}'
            if path in names: return path
    raise KeyError(resource)


def nptc(data):
    pos = 8
    while pos < len(data):
        length = struct.unpack_from('>I', data, pos)[0]
        if data[pos + 4:pos + 8] == b'npTc':
            chunk = data[pos + 8:pos + 8 + length]
            nx, ny = chunk[1], chunk[2]
            pad = struct.unpack_from('>4i', chunk, 12)  # left, right, top, bottom
            xs = struct.unpack_from(f'>{nx}i', chunk, 32)
            ys = struct.unpack_from(f'>{ny}i', chunk, 32 + 4 * nx)
            return pad, xs, ys
        pos += length + 12
    return None


def size(data):
    return struct.unpack_from('>II', data, 16)


def dp(px, per_dp=1.5):
    return '0' if not px else f'calc({px / per_dp:g} * var(--dp))'


def per_dp(path):
    folder = path.split('/')[1]
    return 1.5 if '-hdpi' in folder or '-nodpi' in folder else 0.75 if '-ldpi' in folder else 1.0


def main():
    # docs/data/ec-assets.tsv, and the lists other generators write next to it (ec-assets-<name>.tsv)
    lists = ['docs/data/ec-assets.tsv'] + sorted(f'docs/data/{f}' for f in os.listdir(ROOT + 'docs/data') if f.startswith('ec-assets-') and f.endswith('.tsv'))
    rows = [line.rstrip('\n').split('\t') for path in lists for line in open(ROOT + path, encoding='utf-8')
            if line.strip() and not line.startswith('#')]
    zips, css = {}, []
    os.makedirs(OUT, exist_ok=True)
    for out, apk, resource in rows:
        z = zips.setdefault(apk, zipfile.ZipFile(SYSTEM + apk))
        path = find(z, resource)
        data = z.read(path)
        open(OUT + out, 'wb').write(data)
        if out.endswith('.9.png'):
            info = nptc(data)
            if not info: raise SystemExit(f'{out}: no npTc chunk')
            (pl, pr, pt, pb), xs, ys = info
            if len(xs) > 2 or len(ys) > 2:
                print(f'note: {out} has {len(xs) // 2} x {len(ys) // 2} stretch areas; its class stretches only between the outer ones')
            w, h = size(data)
            left, right = (xs[0], w - xs[-1]) if xs else (0, 0)
            top, bottom = (ys[0], h - ys[-1]) if ys else (0, 0)
            cls, k = out[:-len('.9.png')], per_dp(path)
            css.append(f'.np-{cls}{{box-sizing:border-box;border-style:solid;border-color:transparent;'
                       f'border-width:{dp(top, k)} {dp(right, k)} {dp(bottom, k)} {dp(left, k)};'
                       f"border-image:url('assets/{out}') {top} {right} {bottom} {left} fill / "
                       f'{dp(top, k)} {dp(right, k)} {dp(bottom, k)} {dp(left, k)} stretch;'
                       f'padding:{dp(max(0, pt - top), k)} {dp(max(0, pr - right), k)} {dp(max(0, pb - bottom), k)} {dp(max(0, pl - left), k)}}}'
                       f'  /* {path} {w}x{h} */')
            # the view's padding when the nine-patch is its background (View.setBackgroundDrawable takes it)
            css.append(f'.npp-{cls}{{padding:{dp(pt, k)} {dp(pr, k)} {dp(pb, k)} {dp(pl, k)}}}')
    head = ('/* Generated by docs/tools/ec-assets.py from docs/data/ec-assets.tsv: the Nexus One image\'s nine-patches as CSS border\n'
            '   images (stretch areas and padding from each PNG\'s npTc chunk, hdpi and nodpi pixels / 1.5, mdpi / 1 = dp). Do not edit by hand. */\n')
    open(CSS, 'w', encoding='utf-8', newline='\n').write(head + '\n'.join(css) + '\n')
    print(len(rows), 'files,', len(css) // 2, 'nine-patches')


if __name__ == '__main__':
    main()
