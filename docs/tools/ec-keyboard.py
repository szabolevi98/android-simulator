"""Writes versions/2.1/ec-keyboard-data.js: the Nexus One image's on-screen keyboard (VoiceSearchWithKeyboard.apk, LatinIME
with voice) as EC.keyboardXml = {<name>: {keyHeight, rows: [{mode, keys: [{codes, label, icon, width, gap, edge, modifier,
sticky, repeatable, popup}]}]}} for res/xml/kbd_qwerty, kbd_symbols, kbd_symbols_shift, kbd_popup_template and the
German / French qwerty (res/xml-de, res/xml-fr). Widths and gaps are fractions of the keyboard width (%p); keyHeight is dp.
String references (popupCharacters) resolve to the image's default text.
    python docs/tools/ec-keyboard.py"""
import html, json, re
from loguru import logger; logger.remove()
from androguard.core.apk import APK
from androguard.core.axml import AXMLPrinter
ROOT = __file__.replace('\\', '/').rsplit('/docs/', 1)[0] + '/'
apk = APK(f'{ROOT}_aosp/passion/system/app/VoiceSearchWithKeyboard.apk')
res = apk.get_android_resources()
names = res.get_packages_names()
pkg = next((p for p in names if p != 'android'), names[0])


STRINGS = res.get_resolved_strings().get(pkg, {}).get('DEFAULT', {})


def resolve(value):
    """A reference: the image's default text for a string, else its type/name (dimen/key_height …)."""
    m = re.fullmatch(r'@(?:android:)?([0-9A-Fa-f]{8})', html.unescape(value or ''))
    if not m: return value
    rid = int(m.group(1), 16)
    if rid in STRINGS: return STRINGS[rid]
    try: return res.get_resource_xml_name(rid).lstrip('@').split(':')[-1]
    except Exception: return value


def text(v):
    return html.unescape(resolve(v)) if v is not None else None


def frac(v):
    if v is None: return None
    m = re.fullmatch(r'([\d.]+)%p', v)
    return float(m.group(1)) / 100 if m else v


def parse(path):
    xml = AXMLPrinter(apk.get_file(path)).get_xml().decode('utf-8')
    attrs = lambda tag: dict(re.findall(r'(?:android:)?(\w+)="([^"]*)"', tag))
    out = {'rows': []}
    for tag in re.findall(r'<(?:Keyboard|Row|Key)\b[^>]*>', xml):
        a = attrs(tag)
        if tag.startswith('<Keyboard'):
            out['keyHeight'] = a.get('keyHeight'); out['keyWidth'] = frac(a.get('keyWidth'))
        elif tag.startswith('<Row'):
            out['rows'].append({'mode': resolve(a.get('keyboardMode')), 'edge': a.get('rowEdgeFlags'), 'keys': []})
        else:
            key = {k: v for k, v in {
                'codes': a.get('codes'), 'label': text(a.get('keyLabel')), 'icon': resolve(a.get('keyIcon')), 'width': frac(a.get('keyWidth')),
                'gap': frac(a.get('horizontalGap')), 'edge': a.get('keyEdgeFlags'), 'modifier': a.get('isModifier') == 'true' or None,
                'sticky': a.get('isSticky') == 'true' or None, 'repeatable': a.get('isRepeatable') == 'true' or None,
                'popup': text(a.get('popupCharacters')), 'output': text(a.get('keyOutputText'))}.items() if v not in (None, '')}
            out['rows'][-1]['keys'].append(key)
    return out


files = {'qwerty': 'res/xml/kbd_qwerty.xml', 'symbols': 'res/xml/kbd_symbols.xml', 'symbols_shift': 'res/xml/kbd_symbols_shift.xml',
         'qwerty_de': 'res/xml-de/kbd_qwerty.xml', 'qwerty_fr': 'res/xml-fr/kbd_qwerty.xml', 'popup': 'res/xml/kbd_popup_template.xml'}
data = {name: parse(path) for name, path in files.items()}
js = ('/* Generated by docs/tools/ec-keyboard.py from the Nexus One image\'s VoiceSearchWithKeyboard.apk (LatinIME). */\n'
      f'EC.keyboardXml = {json.dumps(data, ensure_ascii=False, separators=(",", ":"))};\n')
open(f'{ROOT}versions/2.1/ec-keyboard-data.js', 'w', encoding='utf-8', newline='\n').write(js)
for name, d in data.items(): print(name, d.get('keyHeight'), [len(r['keys']) for r in d['rows']], [r['mode'] for r in d['rows']])
