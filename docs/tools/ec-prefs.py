"""Android 2.1: the Settings app's preference screens from the Nexus One image (Settings.apk res/xml, ERE27).

    python docs/tools/ec-prefs.py

Writes
  versions/2.1/ec-settings-data.js   EC.settingsXml = {<xml name>: node}; a node is {t: tag, key, title, summary, summaryOn,
                                     summaryOff, entries, entryValues, dependency, defaultValue, icon, dialogTitle, intent,
                                     order, disableDependentsState, ..., c: [children]} with every resource reference as its
                                     name ("string/sound_settings", "array/animations_entries", "drawable/ic_settings_wireless")
  versions/2.1/ec-strings-settings.js  the strings and arrays those screens name (docs/tools/ec-strings.py rules)
  docs/data/ec-assets-settings.tsv   the drawables they name, for docs/tools/ec-assets.py
Do not edit the outputs by hand."""
import importlib.util, json, os, re
from loguru import logger; logger.remove()
from androguard.core.apk import APK
from androguard.core.axml import AXMLPrinter

ROOT = __file__.replace('\\', '/').rsplit('/docs/', 1)[0] + '/'
SYSTEM = ROOT + '_aosp/passion/system/'
SCREENS = ['settings', 'wireless_settings', 'wifi_settings', 'wifi_advanced_settings', 'bluetooth_settings', 'sound_and_display_settings',
           'security_settings', 'application_settings', 'development_prefs', 'privacy_settings', 'device_info_memory', 'language_settings',
           'keyboard_settings', 'accessibility_settings', 'tts_settings', 'date_time_prefs', 'device_info_settings', 'device_info_status',
           'quick_launch_settings', 'dock_settings', 'input_methods_prefs', 'sim_lock_settings', 'vpn_settings', 'apn_settings',
           'power_usage_summary']
SETTINGS, FRAMEWORK = APK(SYSTEM + 'app/Settings.apk'), APK(SYSTEM + 'framework/framework-res.apk')
RS, RF = SETTINGS.get_android_resources(), FRAMEWORK.get_android_resources()
ATTRS = ['key', 'title', 'summary', 'summaryOn', 'summaryOff', 'entries', 'entryValues', 'dependency', 'defaultValue', 'icon',
         'dialogTitle', 'dialogMessage', 'dialogIcon', 'order', 'disableDependentsState', 'persistent', 'enabled', 'selectable', 'streamType',
         'ringtoneType', 'showDefault', 'showSilent', 'positiveButtonText', 'negativeButtonText', 'layout', 'widgetLayout']
strings, arrays, drawables = set(), set(), set()


def ref(value):
    """'@7F090180' -> 'string/sound_settings' (Settings), '@0104000A' -> 'string/ok' (framework)."""
    if not isinstance(value, str) or not re.fullmatch(r'@[0-9A-Fa-f]{8}', value): return value
    rid = int(value[1:], 16)
    res = RF if rid >> 24 == 1 else RS
    name = res.get_resource_xml_name(rid)
    if not name: return value
    name = name.split(':', 1)[-1].lstrip('@')
    kind = name.split('/')[0]
    if kind == 'string': strings.add((name.split('/')[1], 'framework' if rid >> 24 == 1 else 'Settings'))
    elif kind == 'array': arrays.add((name.split('/')[1], 'framework' if rid >> 24 == 1 else 'Settings'))
    elif kind == 'drawable': drawables.add((name.split('/')[1], 'framework' if rid >> 24 == 1 else 'Settings'))
    return name


def values(value):
    rid = int(value[1:], 16)
    res = RF if rid >> 24 == 1 else RS
    for config, entry in res.get_res_configs(rid):
        if (config.get_qualifier() or '') == '':
            out = []
            for _, item in entry.item.items:
                out.append(res.stringpool_main.getString(item.data) if item.data_type == 3 else str(item.data))
            return out
    return []


def node(e):
    out = {'t': e.tag.split('.')[-1]}
    for k, v in e.attrib.items():
        name = k.split('}')[-1]
        if name == 'entryValues' and isinstance(v, str) and v.startswith('@'):
            out[name] = values(v)   # values, not texts: kept as they are
        elif name in ATTRS: out[name] = ref(v)
    kids = []
    for ch in e:
        if ch.tag == 'intent':
            out['intent'] = {k.split('}')[-1]: v for k, v in ch.attrib.items()}
        elif ch.tag == 'extra':
            continue
        else:
            kids.append(node(ch))
    if kids: out['c'] = kids
    return out


def main():
    data = {}
    for name in SCREENS:
        path = f'res/xml/{name}.xml'
        if path not in SETTINGS.get_files(): continue
        data[name] = node(AXMLPrinter(SETTINGS.get_file(path)).get_xml_obj())
    # Each activity's android:label: the window title of its screen.
    NS = '{http://schemas.android.com/apk/res/android}'
    labels = {}
    for act in SETTINGS.get_android_manifest_xml().iter('activity'):
        lab = act.get(NS + 'label')
        if lab: labels[act.get(NS + 'name').split('.')[-1]] = ref(lab)
    head = ('/* Generated by docs/tools/ec-prefs.py from the Nexus One ERE27 image\'s Settings.apk res/xml: every preference screen\n'
            '   with its resources by name (the texts are in ec-strings-settings.js). Do not edit. */\n')
    open(ROOT + 'versions/2.1/ec-settings-data.js', 'w', encoding='utf-8', newline='\n').write(
        head + 'EC.settingsXml = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n'
        + 'EC.settingsLabels = ' + json.dumps(labels, ensure_ascii=False, separators=(',', ':')) + ';\n')
    # the texts, through docs/tools/ec-strings.py's rules
    spec = importlib.util.spec_from_file_location('ec_strings', ROOT + 'docs/tools/ec-strings.py')
    es = importlib.util.module_from_spec(spec); spec.loader.exec_module(es)
    keys = [f'{apk}/{n}' if apk == 'framework' else n for n, apk in sorted(strings)]
    keys += [f'array:{apk}/{n}' if apk == 'framework' else f'array:{n}' for n, apk in sorted(arrays)]
    es.build('settings', {'apks': ['Settings', 'framework'], 'keys': keys})
    rows = ['# Settings drawables named by its preference screens (written by docs/tools/ec-prefs.py)']
    for n, apk in sorted(drawables):
        rows.append(f'st-{n}.png\t{"framework/framework-res.apk" if apk == "framework" else "app/Settings.apk"}\tdrawable/{n}')
    open(ROOT + 'docs/data/ec-assets-settings.tsv', 'w', encoding='utf-8', newline='\n').write('\n'.join(rows) + '\n')
    print(len(data), 'screens,', len(strings), 'strings,', len(arrays), 'arrays,', len(drawables), 'drawables')


if __name__ == '__main__':
    main()
