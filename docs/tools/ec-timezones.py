"""Writes versions/2.1/ec-timezones.js: the time zones of the Nexus One image's Settings ZoneList (res/xml*/timezones.xml)
as EC.timeZones = [[id, en, hu, de, fr, es], ...] in the file's order. The image has no Hungarian: hu is the Nexus S
(2.3.6) name where its English name for the zone is the same, else docs/data/ec-hu.tsv (key "tz:<id>"), else English.
    python docs/tools/ec-timezones.py"""
import csv, json, re
from loguru import logger; logger.remove()
from androguard.core.apk import APK
from androguard.core.axml import AXMLPrinter
ROOT = __file__.replace('\\', '/').rsplit('/docs/', 1)[0] + '/'


def zones(apk, path):
    if path not in apk.get_files(): return {}
    xml = AXMLPrinter(apk.get_file(path)).get_xml().decode('utf-8')
    return dict(re.findall(r'<timezone id="([^"]+)"[^>]*>([^<]*)</timezone>', xml))


passion = APK(f'{ROOT}_aosp/passion/system/app/Settings.apk')
crespo = APK(f'{ROOT}_aosp/crespo/system/app/Settings.apk')
base = zones(passion, 'res/xml/timezones.xml')
local = {lang: zones(passion, f'res/xml-{lang}/timezones.xml') for lang in ('de', 'fr', 'es')}
gb_en, gb_hu = zones(crespo, 'res/xml/timezones.xml'), zones(crespo, 'res/xml-hu/timezones.xml')
own = {}
for row in csv.reader(open(f'{ROOT}docs/data/ec-hu.tsv', encoding='utf-8'), delimiter='\t'):
    if row and row[0].startswith('tz:'): own[row[0][3:]] = row[1]
rows, missing = [], []
for zid, name in base.items():
    hu = gb_hu.get(zid) if gb_en.get(zid) == name and zid in gb_hu else own.get(zid)
    if hu is None: missing.append((zid, name)); hu = name
    rows.append([zid, name, hu] + [local[lang].get(zid, name) for lang in ('de', 'fr', 'es')])
js = ('/* Generated by docs/tools/ec-timezones.py from the Nexus One image\'s Settings (timezones.xml): [id, en, hu, de, fr, es];\n'
      '   hu from the Nexus S image where the English matches, else docs/data/ec-hu.tsv. */\n'
      f'EC.timeZones = {json.dumps(rows, ensure_ascii=False, separators=(",", ":"))};\n')
open(f'{ROOT}versions/2.1/ec-timezones.js', 'w', encoding='utf-8', newline='\n').write(js)
print(len(rows), 'zones;', len(missing), 'without Hungarian:', missing)
