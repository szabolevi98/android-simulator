"""Writes versions/2.1/ec-webpages.js: the WebView's own "Web page not available" page (framework-res res/raw*/nodomain.html,
what the Nexus One's browser shows for a site it cannot reach) as EC.webErrorPage = {lang: body HTML with %s for the
address}, and copies its image (framework-res assets/webkit/android-weberror.png) to versions/2.1/assets. The image has
no Hungarian; the Nexus S 2.3.6 framework's res/raw-hu/nodomain.html is used, its English page being the same.
    python docs/tools/ec-webpages.py"""
import json, re, zipfile
ROOT = __file__.replace('\\', '/').rsplit('/docs/', 1)[0] + '/'
passion = zipfile.ZipFile(f'{ROOT}_aosp/passion/system/framework/framework-res.apk')
crespo = zipfile.ZipFile(f'{ROOT}_aosp/crespo/system/framework/framework-res.apk')


def body(z, path):
    html = z.read(path).decode('utf-8')
    inner = re.search(r'<body>(.*?)</body>', html, re.S).group(1)
    inner = inner.replace('file:///android_asset/webkit/android-weberror.png', 'assets/fw-android-weberror.png')
    return re.sub(r'\s+', ' ', inner).strip()


en = body(passion, 'res/raw/nodomain.html')
assert en == body(crespo, 'res/raw/nodomain.html'), 'the Nexus S English page differs'
pages = {'en': en, **{lang: body(passion, f'res/raw-{lang}/nodomain.html') for lang in ('de', 'fr', 'es')}, 'hu': body(crespo, 'res/raw-hu/nodomain.html')}
open(f'{ROOT}versions/2.1/assets/fw-android-weberror.png', 'wb').write(passion.read('assets/webkit/android-weberror.png'))
js = ('/* Generated by docs/tools/ec-webpages.py: the WebView\'s nodomain.html (framework-res, ERE27; hu from the Nexus S). */\n'
      f'EC.webErrorPage = {json.dumps(pages, ensure_ascii=False)};\n')
open(f'{ROOT}versions/2.1/ec-webpages.js', 'w', encoding='utf-8', newline='\n').write(js)
print({k: len(v) for k, v in pages.items()})
